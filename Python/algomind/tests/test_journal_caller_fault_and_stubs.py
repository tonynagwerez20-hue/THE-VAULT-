"""Offline contract checks and serialized recovery models for AMIGO lifecycle and execution boundaries.

Label: CONTRACT EXAMPLES AND PERSISTED-ARTIFACT MODELS.
Not a native MQL5 runtime test, live concurrency engine, or crash durability proof.

Covers:
1. Strict model execution outcome dispatch:
   - Requires finite, strictly positive volume and price before confirmation or exposure registration.
   - Zero, negative, NaN, non-finite volume or price yields RISK_OP_UNCERTAIN (or REJECTED if unaccepted).
   - Separates UNCERTAIN, REJECTED (e.g. preflight risk guard), SHADOW, and CONFIRMED.
2. Actual serialized journal on-disk persistence and retrieval under payload truncation:
   - Uses the actual framing protocol from TransactionRecon.mqh (length-prefixed UTF-16 units).
   - Persists a damaged/truncated payload directly into an on-disk SQLite database file.
   - Closes the connection, reopens the on-disk database file from disk, retrieves the damaged record,
     and validates that unframing fails with ValueError("truncated payload").
   - Explicitly distinguishes payload-level truncation from database-file filesystem corruption.
3. Transcribed Python predicate for ReconLedgerPairConsistent:
   - Accurately labeled as a Python transcription of the MQL5 rules, not native MQL5 execution.
   - Enforces exact risk_outcome == journal_outcome when journal_id == risk_id.
   - Enforces that pending/uncertain risk states (1=RESERVED, 5=UNCERTAIN) are NEVER consistent.
   - Enforces that confirmed execution (4) requires matching stage=2 journal evidence.
4. Separate external-snapshot publication test:
   - Distinct from journal recovery. Validates format generated by WriteSnapshotForExternal.
"""

