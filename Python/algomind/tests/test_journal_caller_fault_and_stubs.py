# --- Journal Framing Oracle (Exact UTF-16 length-prefixed framing from TransactionRecon.mqh) ---

def frame_journal_fields(fields: list[str]) -> str:
    """UTF-16 code units match MQL5 StringLen, matching ReconFormatIntentPayload."""
    return "".join(f"{len(f.encode('utf-16-le')) // 2}:{f}" for f in fields)


def unframe_journal_payload(payload: str) -> list[str]:
    """Unframes UTF-16 length-prefixed journal payload, raising ValueError on corruption or truncation."""
    units = payload.encode("utf-16-le")
    cursor = 0
    fields = []
    if len(units) > 32768:
        raise ValueError("oversize payload")
    for _ in range(9):
        separator = units.find(b":\x00", cursor)
        if separator < cursor or (separator - cursor) // 2 > 5:
            raise ValueError("length prefix missing or corrupted")
        length_text = units[cursor:separator].decode("utf-16-le")
        if not length_text.isdigit():
            raise ValueError("non-numeric length prefix")
        length = int(length_text)
        if str(length) != length_text or length < 0:
            raise ValueError("non-canonical length")
        end = separator + 2 + length * 2
        if end > len(units):
            raise ValueError("truncated payload: unexpected end of stream")
        fields.append(units[separator + 2:end].decode("utf-16-le"))
        cursor = end
    if cursor != len(units):
        raise ValueError("extra corrupted trailing data")
    return fields


# --- Extraction of SQL from TransactionRecon.mqh ---

def extract_strings(body: str) -> str:
    return "".join(re.findall(r'"([^"\n]*)"', body))

JOURNAL_SCHEMA = extract_strings(
    RECON.split("string ReconJournalDDL()", 1)[1].split("bool ReconCheckSingleValue(", 1)[0]
)
JOURNAL_PREPARE_SQL = extract_strings(
    RECON.split("string sql=", 1)[1].split("int stmt=", 1)[0]
)
JOURNAL_FINISH_SQL = extract_strings(
    RECON.split("bool ReconFinishOpportunity(", 1)[1].split("int stmt=DatabasePrepare(g_recon_db,", 1)[1].split(");", 1)[0]
)


def _is_finite_positive(val) -> bool:
    """Validates that a numeric value is finite, numeric, and strictly positive (> 0.0)."""
    return isinstance(val, (int, float)) and math.isfinite(val) and val > 0.0


# --- Execution Dispatcher with Strict Validity Checks ---

def evaluate_execution_handler(er: dict, shadow_only: bool = False) -> tuple[str, dict]:
    """Strict execution result dispatcher mirroring AMIGO OnClosedBar contracts:
    - outcome_uncertain=True -> RISK_OP_UNCERTAIN (registers exposure only if pos_id>0 and finite positive volume & price).
    - accepted=False -> RISK_OP_REJECTED (zero exposure).
    - accepted=True, shadow_only=True -> RISK_OP_SHADOW (requires finite positive volume and entry price).
    - accepted=True, shadow_only=False -> requires position_id > 0 AND finite positive volume AND finite positive price.
      If position_id == 0, volume <= 0, price <= 0, or either is NaN/infinite -> returns RISK_OP_UNCERTAIN (latch state fault).
    """
    if er.get("outcome_uncertain"):
        registered = {}
        vol = er.get("fill_volume")
        price = er.get("fill_price")
        pos_id = er.get("position_id", 0)
        if er.get("accepted") and isinstance(pos_id, int) and pos_id > 0 and _is_finite_positive(vol) and _is_finite_positive(price):
            registered = {
                "position_id": pos_id,
                "volume": vol,
                "price": price
            }
        return "RISK_OP_UNCERTAIN", registered

    if not er.get("accepted"):
        return "RISK_OP_REJECTED", {}

    vol = er.get("fill_volume")
    price = er.get("fill_price")
    pos_id = er.get("position_id", 0)

    if shadow_only:
        if not _is_finite_positive(vol) or not _is_finite_positive(price):
            return "RISK_OP_REJECTED", {}
        return "RISK_OP_SHADOW", {
            "position_id": 9999,
            "volume": vol,
            "price": price
        }

    # Confirmed fill strictly requires valid position ticket, finite positive volume, and finite positive price
    if not (isinstance(pos_id, int) and pos_id > 0 and _is_finite_positive(vol) and _is_finite_positive(price)):
        # Invalid fills (e.g. pos_id=0, NaN/zero/negative volume or price) must NEVER be confirmed.
        # They latch an admission fault and return RISK_OP_UNCERTAIN.
        return "RISK_OP_UNCERTAIN", {}

    return "RISK_OP_CONFIRMED", {
        "position_id": pos_id,
        "volume": vol,
        "price": price
    }


# --- Transcribed Python Predicate for Production Ledger-Pair Rules ---

def transcribed_recon_ledger_pair_consistent(risk_id: int, risk_outcome: int,
                                            present: bool, journal_id: int,
                                            stage: int, journal_outcome: int) -> bool:
    """Transcribed Python reference for ReconLedgerPairConsistent() in TransactionRecon.mqh:
    
    // Outcome enum values:
    // 0: NONE, 1: RESERVED, 2: REJECTED, 3: NO_TRADE, 4: CONFIRMED, 5: UNCERTAIN, 6: SHADOW
    """
    if risk_id < 0 or risk_outcome < 0 or risk_outcome > 6:
        return False
    if (risk_id == 0) != (risk_outcome == 0):
        return False
    if risk_outcome == 1 or risk_outcome == 5:
        return False
    if not present:
        return risk_outcome != 4
    if journal_id <= 0 or stage != 2 or (journal_outcome != 2 and journal_outcome != 4):
        return False
    if journal_id > risk_id:
        return False
    if journal_id == risk_id:
        return risk_outcome == journal_outcome
    return risk_outcome in (2, 3, 6)


class TestJournalCallerFaultAndStubs(unittest.TestCase):
    """Refined offline contract tests with on-disk truncation and strict numeric validation."""

    def test_execution_handler_rejects_non_finite_and_zero_price_or_volume(self):
        """Confirmed fills must have finite, strictly positive volume and price; otherwise UNCERTAIN."""
        # 1. Probe case: NaN volume and zero price -> MUST NOT BE CONFIRMED (must be UNCERTAIN)
        er_probe = {
            "accepted": True,
            "outcome_uncertain": False,
            "position_id": 12345,
            "fill_volume": float("nan"),
            "fill_price": 0.0
        }
        outcome, reg = evaluate_execution_handler(er_probe, shadow_only=False)
        self.assertEqual(outcome, "RISK_OP_UNCERTAIN", "NaN volume or zero price must never be confirmed")
        self.assertEqual(len(reg), 0)

        # 2. Infinite volume or negative price -> UNCERTAIN
        er_inf = {
            "accepted": True,
            "outcome_uncertain": False,
            "position_id": 12345,
            "fill_volume": float("inf"),
            "fill_price": 2650.0
        }
        outcome, reg = evaluate_execution_handler(er_inf, shadow_only=False)
        self.assertEqual(outcome, "RISK_OP_UNCERTAIN")

        er_neg_price = {
            "accepted": True,
            "outcome_uncertain": False,
            "position_id": 12345,
            "fill_volume": 0.10,
            "fill_price": -2650.0
        }
        outcome, reg = evaluate_execution_handler(er_neg_price, shadow_only=False)
        self.assertEqual(outcome, "RISK_OP_UNCERTAIN")

        # 3. Position ID = 0 -> UNCERTAIN
        er_zero_id = {
            "accepted": True,
            "outcome_uncertain": False,
            "position_id": 0,
            "fill_volume": 0.10,
            "fill_price": 2650.0
        }
        outcome, reg = evaluate_execution_handler(er_zero_id, shadow_only=False)
        self.assertEqual(outcome, "RISK_OP_UNCERTAIN")

        # 4. Valid finite positive volume, price, and position_id -> CONFIRMED
        er_valid = {
            "accepted": True,
            "outcome_uncertain": False,
            "position_id": 12345,
            "fill_volume": 0.10,
            "fill_price": 2650.0
        }
        outcome, reg = evaluate_execution_handler(er_valid, shadow_only=False)
        self.assertEqual(outcome, "RISK_OP_CONFIRMED")
        self.assertEqual(reg["position_id"], 12345)
        self.assertEqual(reg["volume"], 0.10)
        self.assertEqual(reg["price"], 2650.0)

        # 5. Uncertain result with NaN volume -> zero exposure registered
        er_unc_nan = {
            "accepted": True,
            "outcome_uncertain": True,
            "position_id": 12345,
            "fill_volume": float("nan"),
            "fill_price": 2650.0
        }
        outcome_unc, reg_unc = evaluate_execution_handler(er_unc_nan, shadow_only=False)
        self.assertEqual(outcome_unc, "RISK_OP_UNCERTAIN")
        self.assertEqual(len(reg_unc), 0, "No exposure registered for non-finite volume")

    def test_on_disk_journal_persistence_and_retrieval_under_payload_truncation(self):
        """Persists both valid and damaged payloads to disk in an actual SQLite database file,
        closes and reopens the database from disk, and verifies parsing behavior.
        
        Note: This tests application payload truncation within a valid SQLite database file.
        Database-file corruption (e.g. corrupt SQLite header/pages) is a distinct failure mode.
        """
        canonical_fields = [
            "AMIGO_INTENT_V1", "XAUUSD", "BUY_CONTINUATION", "XAUUSD", "Amigo-Test",
            "100|100|101|1|1|0|1|100|160|1|1|3|0", "2650.00|2640.00|2670.00|0.8|0.7|0.5|1",
            "1|20260908|0|0|20|0.01|2650.00|2640.00|2670.00", "1000|10|0|0.5|2|5|2|0.5|1.5|1|1|0|24"
        ]
        framed_valid = frame_journal_fields(canonical_fields)
        framed_truncated = framed_valid[:len(framed_valid) // 2]  # Physically truncated payload

        with tempfile.TemporaryDirectory() as tmp_dir:
            db_path = Path(tmp_dir) / "test_execution_journal.sqlite"

            # Step 1: Open, initialize schema, write valid and truncated records, commit, close
            conn1 = sqlite3.connect(db_path)
            conn1.execute(JOURNAL_SCHEMA)
            conn1.execute(JOURNAL_PREPARE_SQL, ("account1:XAUUSD", "account1", 101, framed_valid))
            conn1.execute(JOURNAL_PREPARE_SQL, ("account2:EURUSD", "account2", 102, framed_truncated))
            conn1.commit()
            conn1.close()

            # Step 2: Reopen from disk in a fresh connection (retrieval from disk)
            conn2 = sqlite3.connect(db_path)
            try:
                # Retrieve valid record from disk
                row_valid = conn2.execute("SELECT payload FROM execution_journal_v1 WHERE intent=101").fetchone()
                self.assertIsNotNone(row_valid)
                unframed_valid = unframe_journal_payload(row_valid[0])
                self.assertEqual(unframed_valid, canonical_fields)

                # Retrieve damaged/truncated record from disk
                row_damaged = conn2.execute("SELECT payload FROM execution_journal_v1 WHERE intent=102").fetchone()
                self.assertIsNotNone(row_damaged)
                with self.assertRaises(ValueError) as ctx:
                    unframe_journal_payload(row_damaged[0])
                self.assertIn("truncated payload", str(ctx.exception))
            finally:
                conn2.close()

    def test_transcribed_recon_ledger_pair_consistency_rules(self):
        """Tests transcribed Python predicate for ReconLedgerPairConsistent across restart scenarios."""
        # 1. Fresh startup: risk=0, journal absent -> True
        self.assertTrue(transcribed_recon_ledger_pair_consistent(0, 0, False, 0, -1, -1))

        # 2. Risk has pending reservation (1=RESERVED or 5=UNCERTAIN) -> Always False
        self.assertFalse(transcribed_recon_ledger_pair_consistent(10, 1, False, 0, -1, -1))
        self.assertFalse(transcribed_recon_ledger_pair_consistent(10, 1, True, 10, 2, 4))
        self.assertFalse(transcribed_recon_ledger_pair_consistent(10, 5, True, 10, 1, 0))

        # 3. Risk is CONFIRMED (4), but journal record is absent -> False
        self.assertFalse(transcribed_recon_ledger_pair_consistent(10, 4, False, 0, -1, -1))

        # 4. Risk is CONFIRMED (4), journal has matching stage=2 outcome=4 -> True
        self.assertTrue(transcribed_recon_ledger_pair_consistent(10, 4, True, 10, 2, 4))

        # 5. Risk is CONFIRMED (4), but journal has outcome=2 (REJECTED) -> False
        self.assertFalse(transcribed_recon_ledger_pair_consistent(10, 4, True, 10, 2, 2))

        # 6. Risk is REJECTED (2), journal has matching stage=2 outcome=2 -> True
        self.assertTrue(transcribed_recon_ledger_pair_consistent(10, 2, True, 10, 2, 2))

        # 7. Risk is NO_TRADE (3), journal has older submission (9, stage=2, outcome=4) -> True (need no submission)
        self.assertTrue(transcribed_recon_ledger_pair_consistent(10, 3, True, 9, 2, 4))

        # 8. Journal is ahead of risk (journal_id > risk_id) -> False
        self.assertFalse(transcribed_recon_ledger_pair_consistent(10, 2, True, 11, 2, 2))

        # 9. Journal has incomplete stage (stage=1) -> False
        self.assertFalse(transcribed_recon_ledger_pair_consistent(10, 4, True, 10, 1, 0))

